// Pure local model. Admission is an evidence contract, not a YouTube verifier.
export function admission(video, recording, edition, entry) {
  const fail = reason => ({ allowed: false, reason });
  if (!video || !recording) return fail('Official recording not sourced');
  if (video.testOnly !== false) return fail('Test-only source — playback disabled');
  const e = video.officialEvidence;
  if (!e || !validHttps(e.sourceUrl) || !validDate(e.checkedAt)
      || e.reviewed !== true || !e.reviewer || e.videoId !== video.id) return fail('Official source evidence incomplete');
  if (e.channelType === 'provided-music') {
    // Reviewed YouTube metadata: distributor-delivered, autogenerated audio on an OAC.
    // A stable uploader ID is recorded only when observed, never fabricated.
    const u = new URL(e.sourceUrl);
    if (!['www.youtube.com','youtube.com'].includes(u.hostname) || u.pathname !== '/watch'
        || u.searchParams.get('v') !== video.id || !e.providerName?.trim()
        || e.autoGenerated !== true || e.officialArtistBadge !== true)
      return fail('Official distributor evidence incomplete');
  } else if (!['artist','label','topic'].includes(e.channelType)
      || !/^UC[\w-]{22}$/.test(e.channelId || '') || e.channelId !== video.channelId)
    return fail('Official uploader evidence incomplete');
  const m = video.match;
  if (!m || m.reviewed !== true || m.editionId !== edition?.id
      || m.entryId !== entry?.id || m.recordingId !== recording.id
      || entry?.recordingId !== recording.id
      || m.title !== recording.title || m.version !== recording.version
      || !validHttps(m.sourceUrl) || !validDate(m.checkedAt))
    return fail('Exact recording / edition match not established');
  if (!/^[\w-]{11}$/.test(video.id || '')) return fail('Invalid video identifier');
  const a = video.availability;
  if (a?.embeddable === false || ['unavailable','embedding-disabled'].includes(a?.state)) return fail('Unavailable or embedding disabled');
  if (a?.state === 'unchecked') return { allowed:true, reason:'Official source and version reviewed; playback not yet checked' };
  if (a?.state !== 'available' || !validDate(a?.checkedAt) || a?.embeddable !== true) return fail('Playback evidence status missing');
  return { allowed: true, reason: 'Evidence reviewed; runtime availability may still vary' };
}
function validHttps(s) { try { return new URL(s).protocol === 'https:'; } catch { return false; } }
function validDate(s) { return typeof s === 'string' && /^\d{4}-\d{2}-\d{2}T/.test(s) && Number.isFinite(Date.parse(s)); }
export function dateLabel(date) {
  if (date.precision === 'day') return date.value;
  if (date.precision === 'early' || date.precision === 'late') return `${date.year} (${date.precision})`;
  return `${date.year} (day unknown)`;
}
export function chronological(releases) {
  // Editorial order resolves within-year uncertainty; no invented January 1 dates.
  return [...releases].sort((a,b) => a.date.year-b.date.year || a.editorialOrder-b.editorialOrder);
}
let selectionSequence = 0;
export function createQueue(edition) { return { editionId: edition.id, entries: [...edition.entries], index: edition.entries.length ? 0 : -1, generation: ++selectionSequence, status: 'selected' }; }
export function move(q, delta) {
  if (!q.entries.length) return q;
  const index = Math.max(0, Math.min(q.entries.length - 1, q.index + delta));
  return index === q.index ? q : { ...q, index, generation: ++selectionSequence, status: 'selected' };
}
export function receive(q, event) {
  // Future adapter must stamp each callback with the selection generation and entry ID.
  if (event.generation !== q.generation || event.entryId !== q.entries[q.index]?.id) return q;
  if (!['ready','playing','paused','buffering','unstarted','cued','unavailable','ended','error','autoplay-blocked'].includes(event.type)) return q;
  // End/error never advances silently: missing tracks stay represented.
  return { ...q, status: event.type };
}
export function queueCoverage(edition, recordings, videos) {
  const total = edition.entries.length;
  const allowed = edition.entries.filter(x => admission(videos[x.videoKey], recordings[x.recordingId], edition, x).allowed).length;
  const playbackChecked = edition.entries.filter(x => admission(videos[x.videoKey], recordings[x.recordingId], edition, x).allowed && videos[x.videoKey]?.availability?.state === 'available').length;
  return { allowed, total, playbackChecked, complete: total > 0 && allowed === total };
}
